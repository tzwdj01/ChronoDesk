    /**
     * 按中文名、行政区、全拼、拼音首字母搜索城市或县区，并按相关度排序返回。
     */
    fun search(query: String, limit: Int = 15): List<GeocodingItem> {
        val raw = query.trim()
        if (raw.isBlank()) return emptyList()

        val normalized = normalizeQuery(raw)
        val rawLower = raw.lowercase()
        val isAscii = rawLower.all { it in 'a'..'z' || it in '0'..'9' || it == ' ' }

        val scored = records.mapNotNull { rec ->
            val recNameLower = rec.name.lowercase()
            val admin1Norm = normalizeQuery(rec.admin1)
            val admin2Norm = rec.admin2?.let { normalizeQuery(it) } ?: ""

            val score = when {
                recNameLower == rawLower || recNameLower == normalized -> 1000
                isAscii && rec.pinyinFull == rawLower.replace(" ", "") -> 950
                recNameLower.startsWith(normalized) && normalized.isNotEmpty() -> 850
                isAscii && rec.pinyinFull.startsWith(rawLower.replace(" ", "")) -> 820
                isAscii && rawLower.length >= 2 && rec.pinyinInitials == rawLower.replace(" ", "") -> 800
                isAscii && rawLower.length >= 2 && rec.pinyinInitials.startsWith(rawLower.replace(" ", "")) -> 750
                recNameLower.contains(normalized) && normalized.isNotEmpty() -> 700
                admin2Norm.isNotEmpty() && (admin2Norm == normalized || admin2Norm.contains(normalized)) -> 620
                admin1Norm.isNotEmpty() && (admin1Norm == normalized || admin1Norm.contains(normalized)) -> 550
                else -> 0
            }
            if (score > 0) {
                // 相同匹配度时，省会/地级市优先于区县
                val finalScore = score * 10 - rec.importanceRank
                rec to finalScore
            } else null
        }

        return scored
            .sortedByDescending { it.second }
            .take(limit)
            .map { (rec, _) ->
                GeocodingItem(
                    id = rec.id,
                    name = rec.name,
                    latitude = rec.latitude,
                    longitude = rec.longitude,
                    country = rec.country,
                    countryCode = if (rec.country == "中国") "CN" else null,
                    admin1 = rec.admin1,
                    admin2 = rec.admin2
                )
            }
    }

    private fun normalizeQuery(input: String): String {
        var s = input.trim().lowercase().replace(" ", "")
        val suffixes = listOf(
            "特别行政区", "维吾尔自治区", "壮族自治区", "回族自治区", "自治区",
            "自治州", "自治县", "新区", "林区", "地区", "省", "市", "区", "县", "盟", "州"
        )
        for (suffix in suffixes) {
            if (s.length > suffix.length + 1 && s.endsWith(suffix)) {
                s = s.removeSuffix(suffix)
                break
            }
        }
        return s
    }

    /**
     * 按坐标查找距离最近的中国城市或区县（用于无网络或外网逆地理编码不可用时的纯本地中文保底展示）。
     */
    fun findNearestChineseArea(lat: Double, lng: Double, maxDistKm: Double = 65.0): String? {
        if (!lat.isFinite() || !lng.isFinite()) return null
        var bestRecord: CityRecord? = null
        var bestDistKm = Double.MAX_VALUE
        for (rec in records) {
            if (rec.country != "中国" && rec.importanceRank > 4) continue
            val dist = haversineKm(lat, lng, rec.latitude, rec.longitude)
            if (dist < bestDistKm) {
                bestDistKm = dist
                bestRecord = rec
            }
        }
        val match = bestRecord ?: return null
        if (bestDistKm > maxDistKm) return null
        val cityOrCounty = match.admin2?.takeIf { it.isNotBlank() }
            ?: if (match.name.endsWith("市") || match.name.endsWith("区") || match.name.endsWith("县")) match.name else "${match.name}市"
        val parts = listOfNotNull(
            match.admin1.takeIf { it.isNotBlank() && it != cityOrCounty },
            cityOrCounty
        ).distinct()
        return if (parts.isNotEmpty()) "${parts.joinToString(" · ")}附近" else null
    }

    private fun haversineKm(lat1: Double, lng1: Double, lat2: Double, lng2: Double): Double {
        val r = 6371.0
        val dLat = Math.toRadians(lat2 - lat1)
        val dLng = Math.toRadians(lng2 - lng1)
        val a = kotlin.math.sin(dLat / 2) * kotlin.math.sin(dLat / 2) +
            kotlin.math.cos(Math.toRadians(lat1)) * kotlin.math.cos(Math.toRadians(lat2)) *
            kotlin.math.sin(dLng / 2) * kotlin.math.sin(dLng / 2)
        val c = 2 * kotlin.math.atan2(kotlin.math.sqrt(a), kotlin.math.sqrt(1 - a))
        return r * c
    }
